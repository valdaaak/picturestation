function storedLang() {
  try { const l = localStorage.getItem("lang"); return l === "en" || l === "sk" ? l : null; } catch (e) { return null; }
}
const LANG = storedLang()
  || (window.PS_LANG === "en" || window.PS_LANG === "sk" ? window.PS_LANG : null)
  || (/^(sk|cs)\b/i.test(navigator.language || "") ? "sk" : "en");
const LOCALE = () => (LANG === "sk" ? "sk" : "en-GB");

function fmtT(s, p) {
  return p ? s.replace(/\{(\w+)\}/g, (m, k) => (k in p ? String(p[k]) : m)) : s;
}
function t(s, p) {
  const v = LANG === "sk" ? I18N_SK[s] : null;
  return fmtT(typeof v === "string" ? v : s, p);
}
function tn(n, one, other, p) {
  const f = LANG === "sk" ? I18N_SK[other] : null;
  const s = Array.isArray(f) ? (n === 1 ? f[0] : n >= 2 && n <= 4 ? f[1] : f[2]) : (n === 1 ? one : other);
  return fmtT(s, { n, ...(p || {}) });
}

// static texts in index.html: data-t (text), data-t-placeholder, data-t-title, data-t-aria
function applyI18n(root) {
  const r = root || document;
  document.documentElement.lang = LANG;
  r.querySelectorAll("[data-t]").forEach((e) => { e.textContent = t(e.dataset.t); });
  r.querySelectorAll("[data-t-placeholder]").forEach((e) => { e.placeholder = t(e.dataset.tPlaceholder); });
  r.querySelectorAll("[data-t-title]").forEach((e) => { e.title = t(e.dataset.tTitle); });
  r.querySelectorAll("[data-t-aria]").forEach((e) => { e.setAttribute("aria-label", t(e.dataset.tAria)); });
}

applyI18n();
